"""Mod Organizer 2 files as MO2 2.5 really writes them, on real Windows.

The instance is built the way MO2 lays it out on disk: ModOrganizer.ini with Qt @ByteArray values and doubled
backslashes, %BASE_DIR% paths, a UTF-8 BOM, CRLF line ends, separators, a mod name with accents, meta.ini from a Nexus
install, plugins.txt, a real TES4 plugin header with masters, and a profile with its own saves. Checked against Windows:
reading it, turning mods off and back, Undo giving back the exact bytes, refusing while a program named
ModOrganizer.exe runs, a modlist another program holds open, and a read-only modlist.
"""
from __future__ import annotations

import argparse
import hashlib
import os
import shutil
import stat
import subprocess
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import rw_common as rw  # noqa: E402

MODS = ["Unofficial Skyrim Special Edition Patch", "SkyUI", "Immersive Armors", "Café Lighting Überhaul",
        "Bad Textures", "Alternate Start"]


def tes4(masters):
    body = b""
    body += b"HEDR" + (12).to_bytes(2, "little") + b"\x9a\x99\xd9\x3f" + (0).to_bytes(4, "little") + (2048).to_bytes(4, "little")
    for m in masters:
        name = m.encode("cp1252") + b"\0"
        body += b"MAST" + len(name).to_bytes(2, "little") + name
        body += b"DATA" + (8).to_bytes(2, "little") + b"\0" * 8
    return b"TES4" + len(body).to_bytes(4, "little") + b"\0" * 16 + body


def build(base: Path):
    game = base / "Steam" / "steamapps" / "common" / "Skyrim Special Edition"
    game.mkdir(parents=True)
    (game / "SkyrimSE.exe").write_bytes(b"MZ")
    root = base / "MO2 Portable"
    ini_game = str(game).replace("\\", "\\\\")
    (root / "profiles" / "Default").mkdir(parents=True)
    (root / "profiles" / "Survival Run").mkdir(parents=True)
    (root / "ModOrganizer.ini").write_bytes(("\ufeff[General]\r\ngameName=Skyrim Special Edition\r\n"
        f"gamePath=@ByteArray({ini_game})\r\nselected_profile=@ByteArray(Default)\r\nversion=2.5.2\r\n"
        "first_start=false\r\n\r\n[Settings]\r\nbase_directory=%BASE_DIR%\r\nmod_directory=%BASE_DIR%/mods\r\n"
        "profiles_directory=%BASE_DIR%/profiles\r\n").encode("utf-8"))
    for i, name in enumerate(MODS):
        folder = root / "mods" / name
        folder.mkdir(parents=True)
        (folder / "meta.ini").write_bytes((f"[General]\r\ngameName=SkyrimSE\r\nmodid={1000 + i}\r\nversion=1.{i}.0\r\n"
            f"newestVersion=1.{i}.0\r\ninstallationFile={name}-{1000 + i}.7z\r\nurl=\r\n").encode("utf-8"))
        (folder / (name.split()[0] + ".esp")).write_bytes(tes4(["Skyrim.esm", "Update.esm"]))
    (root / "mods" / "Gameplay_separator").mkdir()
    modlist = "# This file was automatically generated by Mod Organizer.\r\n" + "".join(
        f"{'-' if n == 'Bad Textures' else '+'}{n}\r\n" for n in reversed(MODS)) \
        + "+Gameplay_separator\r\n*DLC: Dawnguard\r\n"
    for profile in ("Default", "Survival Run"):
        (root / "profiles" / profile / "modlist.txt").write_bytes(modlist.encode("utf-8"))
        (root / "profiles" / profile / "plugins.txt").write_bytes(
            ("# This file was automatically generated by Mod Organizer.\r\n"
             + "".join(f"*{n.split()[0]}.esp\r\n" for n in MODS if n != "Bad Textures")).encode("utf-8"))
    (root / "profiles" / "Survival Run" / "settings.ini").write_bytes(b"[General]\r\nLocalSaves=true\r\n")
    return root


WAITER = "class Waiter { static void Main() { System.Threading.Thread.Sleep(120000); } }"


def fake_mo2(folder: Path) -> Path:
    """A program named ModOrganizer.exe that just waits, so Windows lists it the way it lists the real one."""
    exe = folder / "ModOrganizer.exe"
    rw.compile_cs(WAITER, exe)
    return exe


def put_back(profile: Path, original: bytes):
    """Leave the list as it started, whatever a failed step did, so the next step is judged on its own."""
    target = profile / "modlist.txt"
    os.chmod(target, stat.S_IREAD | stat.S_IWRITE)
    target.write_bytes(original)
    for p in profile.glob("*.gg-tmp"):
        p.unlink()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, default=Path("_ci_temp/realworld"))
    args = parser.parse_args()
    scratch = rw.isolate("GG-rw-mo2-")
    rep = rw.Report("mo2-real", args.output)
    from gg_desktop import bisect_apply, mymods_core as mc
    root = build(scratch)
    profile = root / "profiles" / "Default"
    original = (profile / "modlist.txt").read_bytes()

    def reading():
        inst = mc.read_instance(root / "ModOrganizer.ini")
        rep.check("the instance is read (game, folders, profiles)", inst.game == "Skyrim Special Edition"
                  and inst.mods_dir == root / "mods" and inst.profiles == ("Default", "Survival Run")
                  and inst.selected == "Default" and inst.game_path and inst.game_path.is_dir(),
                  game=inst.game, game_path=str(inst.game_path), mods=str(inst.mods_dir), profiles=inst.profiles)
        prof = mc.read_profile(inst, "Default")
        names = [m.name for m in prof.mods if m.kind == "mod"]
        rep.check("every mod is listed, accents included, in MO2's order", names == MODS, names=names)
        bad = next(m for m in prof.mods if m.name == "Bad Textures")
        rep.check("turned-off mods read as off, separators and DLC as their own kinds", not bad.enabled
                  and any(m.kind == "separator" for m in prof.mods) and any(m.kind == "base" for m in prof.mods))
        sky = next(m for m in prof.mods if m.name == "SkyUI")
        rep.check("Nexus details come from meta.ini", sky.nexus_id == "1001" and sky.version == "1.1.0",
                  nexus=sky.nexus_id, version=sky.version)
        rep.check("own-saves profiles are noticed", mc.read_profile(inst, "Survival Run").local_saves)
        masters = mc.plugin_masters(root / "mods" / "SkyUI" / "SkyUI.esp")
        rep.check("a plugin's masters are read from its real header", masters == ["Skyrim.esm", "Update.esm"],
                  masters=masters)
    rw.guarded(rep, "reading", reading)

    def change_and_undo():
        mc.set_enabled(profile, ["SkyUI"], False, running=bisect_apply.mo2_running)
        inst = mc.read_instance(root / "ModOrganizer.ini")
        off = not next(m for m in mc.read_profile(inst, "Default").mods if m.name == "SkyUI").enabled
        rep.check("a mod is turned off in the real file", off)
        mc.undo(profile, running=bisect_apply.mo2_running)
        rep.check("Undo gives back the exact original bytes", (profile / "modlist.txt").read_bytes() == original,
                  sha=hashlib.sha256((profile / "modlist.txt").read_bytes()).hexdigest()[:12])
    rw.guarded(rep, "change and undo", change_and_undo)

    def mo2_open():
        exe = fake_mo2(scratch)
        proc = subprocess.Popen([str(exe)])
        try:
            time.sleep(1.5)
            seen = bisect_apply.mo2_running()
            try:
                mc.set_enabled(profile, ["SkyUI"], False, running=bisect_apply.mo2_running)
                refused = ""
            except mc.ModsError as exc:
                refused = str(exc)
            rep.check("with Mod Organizer 2 open, nothing is changed", seen and refused and
                      (profile / "modlist.txt").read_bytes() == original, detected=seen, message=refused[:120])
        finally:
            proc.kill()
            put_back(profile, original)
    rw.guarded(rep, "Mod Organizer 2 open", mo2_open)

    def held_open():
        # Another program reading the list (like a virus scan) for a moment: the change waits and still lands
        import threading
        f = open(profile / "modlist.txt", "rb")
        threading.Timer(0.8, f.close).start()
        mc.set_enabled(profile, ["SkyUI"], False, running=False)
        inst = mc.read_instance(root / "ModOrganizer.ini")
        off = not next(m for m in mc.read_profile(inst, "Default").mods if m.name == "SkyUI").enabled
        mc.undo(profile, running=False)
        rep.check("a list another program has open for a moment is still changed, and undone",
                  off and (profile / "modlist.txt").read_bytes() == original)
        put_back(profile, original)
    rw.guarded(rep, "held open", held_open)

    def read_only():
        target = profile / "modlist.txt"
        os.chmod(target, stat.S_IREAD)
        try:
            try:
                mc.set_enabled(profile, ["SkyUI"], False, running=False)
                outcome = "changed"
            except (mc.ModsError, OSError) as exc:
                outcome = f"refused: {type(exc).__name__}: {exc}"
            same = target.read_bytes() == original
            leftovers = sorted(p.name for p in profile.iterdir() if p.name.endswith(".gg-tmp"))
            rep.check("a read-only list is left as it was, with a clear message and no leftovers",
                      outcome.startswith("refused") and same and not leftovers, outcome=outcome[:200],
                      unchanged=same, leftovers=leftovers)
        finally:
            put_back(profile, original)
    rw.guarded(rep, "read-only list", read_only)
    return rep.finish()


if __name__ == "__main__":
    raise SystemExit(main())
