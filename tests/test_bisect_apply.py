import hashlib
import json
import tempfile
import unittest
from pathlib import Path

from gg_desktop import bisect_apply as ba

MODLIST = ("# This file was automatically generated by Mod Organizer.\n"
           "+Zeta Textures\n-Alpha Script\n+Core Fix\n-Old_separator\n+Weather Pack\n*DLC Base\n")


def tree(root):
    return {p.relative_to(root).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
            for p in sorted(root.rglob("*")) if p.is_file()}


class Case(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.profiles = Path(self._tmp.name) / "profiles"
        self.original = self.profiles / "Default"
        self.original.mkdir(parents=True)
        (self.original / "modlist.txt").write_text(MODLIST, encoding="utf-8", newline="")
        (self.original / "plugins.txt").write_text("*Mod.esp\n", encoding="utf-8")
        (self.original / "loadorder.txt").write_text("Mod.esp\n", encoding="utf-8")
        (self.original / "settings.ini").write_text("[General]\nLocalSaves=false\n", encoding="utf-8")
        (self.original / "saves").mkdir()
        (self.original / "saves" / "slot1.ess").write_bytes(b"SAVE")
        self.never_running = lambda: False


class Copying(Case):
    def test_copy_has_the_files_backups_and_marker_and_the_original_is_unchanged(self):
        before = tree(self.profiles)
        info = ba.make_copy(self.original)
        self.assertEqual(info.folder.name, "GG Bisect - Default")
        for name in ("modlist.txt", "plugins.txt", "loadorder.txt", "settings.ini", ba.MARKER,
                     "GG-original-modlist.txt", "GG-original-plugins.txt"):
            self.assertTrue((info.folder / name).is_file(), name)
        self.assertFalse((info.folder / "saves").exists())
        after = tree(self.original)
        self.assertEqual({k: v for k, v in before.items() if k.startswith("Default")},
                         {"Default/" + k: v for k, v in after.items()})

    def test_copying_twice_reuses_the_same_copy(self):
        first = ba.make_copy(self.original)
        (first.folder / "modlist.txt").write_text("-Zeta Textures\n", encoding="utf-8")
        second = ba.make_copy(self.original)
        self.assertEqual(first.folder, second.folder)
        self.assertEqual((second.folder / "modlist.txt").read_text(encoding="utf-8"), "-Zeta Textures\n")

    def test_a_profile_that_keeps_its_own_saves_is_refused(self):
        (self.original / "settings.ini").write_text("[General]\nLocalSaves=true\n", encoding="utf-8")
        with self.assertRaises(ba.ApplyError) as raised:
            ba.make_copy(self.original)
        self.assertIn("keeps its own saves", str(raised.exception))
        self.assertFalse((self.profiles / "GG Bisect - Default").exists())

    def test_unreadable_settings_are_not_guessed_at(self):
        (self.original / "settings.ini").write_bytes(b"\xff\xfe\x00bad")
        # decodes with cp1252, so it reads as a normal file with no LocalSaves line
        self.assertFalse(ba.keeps_own_saves(self.original))

    def test_a_missing_modlist_is_refused(self):
        (self.original / "modlist.txt").unlink()
        with self.assertRaises(ba.ApplyError):
            ba.make_copy(self.original)

    def test_a_folder_without_our_marker_is_never_written_to(self):
        stranger = self.profiles / "GG Bisect - Default"
        stranger.mkdir()
        (stranger / "modlist.txt").write_text("+Mine\n", encoding="utf-8")
        with self.assertRaises(ba.ApplyError):
            ba.make_copy(self.original)
        with self.assertRaises(ba.ApplyError):
            ba.write_test(stranger, {"Mine"}, running=self.never_running)
        self.assertEqual((stranger / "modlist.txt").read_text(encoding="utf-8"), "+Mine\n")

    def test_the_original_profile_is_never_a_write_target(self):
        with self.assertRaises(ba.ApplyError):
            ba.write_test(self.original, {"Core Fix"}, running=self.never_running)
        self.assertEqual((self.original / "modlist.txt").read_text(encoding="utf-8"), MODLIST)

    def test_a_marker_from_another_version_or_broken_json_is_not_trusted(self):
        info = ba.make_copy(self.original)
        (info.folder / ba.MARKER).write_text("{not json", encoding="utf-8")
        with self.assertRaises(ba.ApplyError):
            ba.write_test(info.folder, {"Core Fix"}, running=self.never_running)
        (info.folder / ba.MARKER).write_text(json.dumps({"version": 99, "source": "Default"}), encoding="utf-8")
        with self.assertRaises(ba.ApplyError):
            ba.write_test(info.folder, {"Core Fix"}, running=self.never_running)

    def test_copy_names_are_made_safe(self):
        self.assertEqual(ba.copy_name('a/b:c*"d'), "GG Bisect - a_b_c__d")
        self.assertEqual(ba.copy_name("..."), "GG Bisect - profile")
        self.assertLessEqual(len(ba.copy_name("x" * 500)), 80)


class Writing(Case):
    def test_exactly_the_chosen_mods_are_on_and_everything_else_keeps_its_place(self):
        info = ba.make_copy(self.original)
        switched = ba.write_test(info.folder, {"core fix", "Weather Pack"}, running=self.never_running)
        self.assertEqual(sorted(switched), ["Core Fix", "Weather Pack"])
        lines = (info.folder / "modlist.txt").read_text(encoding="utf-8").splitlines()
        self.assertEqual(lines, ["# This file was automatically generated by Mod Organizer.",
                                 "-Zeta Textures", "-Alpha Script", "+Core Fix", "-Old_separator",
                                 "+Weather Pack", "*DLC Base"])
        self.assertEqual(ba.enabled_in(info.folder), {"Core Fix", "Weather Pack"})

    def test_each_test_starts_from_the_original_not_the_last_test(self):
        info = ba.make_copy(self.original)
        ba.write_test(info.folder, {"Zeta Textures"}, running=self.never_running)
        ba.write_test(info.folder, {"Alpha Script"}, running=self.never_running)
        self.assertEqual(ba.enabled_in(info.folder), {"Alpha Script"})

    def test_separators_and_base_content_lines_are_left_alone(self):
        text, _ = ba.plan(MODLIST, set())
        self.assertIn("-Old_separator", text)
        self.assertIn("*DLC Base", text)
        text, _ = ba.plan("+Thing_separator\n+Real\n", {"Real"})
        self.assertEqual(text, "+Thing_separator\n+Real\n")

    def test_windows_line_endings_are_kept(self):
        text, _ = ba.plan("# h\r\n+A\r\n-B\r\n", {"B"})
        self.assertEqual(text, "# h\r\n-A\r\n+B\r\n")

    def test_a_mod_that_is_not_in_the_list_stops_the_write(self):
        info = ba.make_copy(self.original)
        with self.assertRaises(ba.ApplyError) as raised:
            ba.write_test(info.folder, {"Core Fix", "Ghost"}, running=self.never_running)
        self.assertIn("Ghost", str(raised.exception))
        self.assertEqual((info.folder / "modlist.txt").read_text(encoding="utf-8"), MODLIST)

    def test_nothing_is_written_while_mo2_is_running(self):
        info = ba.make_copy(self.original)
        with self.assertRaises(ba.ApplyError) as raised:
            ba.write_test(info.folder, {"Core Fix"}, running=lambda: True)
        self.assertIn("Close it completely", str(raised.exception))
        self.assertEqual((info.folder / "modlist.txt").read_text(encoding="utf-8"), MODLIST)

    def test_unknown_running_state_does_not_block(self):
        info = ba.make_copy(self.original)
        ba.write_test(info.folder, {"Core Fix"}, running=lambda: None)
        self.assertEqual(ba.enabled_in(info.folder), {"Core Fix"})

    def test_missing_backup_stops_the_write(self):
        info = ba.make_copy(self.original)
        (info.folder / "GG-original-modlist.txt").unlink()
        with self.assertRaises(ba.ApplyError):
            ba.write_test(info.folder, {"Core Fix"}, running=self.never_running)

    def test_the_original_and_its_saves_are_byte_identical_after_many_tests(self):
        before = tree(self.original)
        info = ba.make_copy(self.original)
        for names in ({"Core Fix"}, set(), {"Zeta Textures", "Alpha Script", "Core Fix", "Weather Pack"}):
            ba.write_test(info.folder, names, running=self.never_running)
        self.assertEqual(tree(self.original), before)
        self.assertEqual(tree(self.original)["saves/slot1.ess"], hashlib.sha256(b"SAVE").hexdigest())

    def test_no_temp_file_is_left_behind(self):
        info = ba.make_copy(self.original)
        ba.write_test(info.folder, {"Core Fix"}, running=self.never_running)
        self.assertFalse((info.folder / "modlist.txt.gg-tmp").exists())

    def test_a_profile_with_no_mods_enabled_still_writes(self):
        info = ba.make_copy(self.original)
        self.assertEqual(ba.write_test(info.folder, set(), running=self.never_running), [])
        self.assertEqual(ba.enabled_in(info.folder), set())


if __name__ == "__main__":
    unittest.main()
