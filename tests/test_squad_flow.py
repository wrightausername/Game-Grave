"""Squad Sync made obvious: codes are found in any paste, the next step is said in words, and the squad profile is a copy."""
from __future__ import annotations

import tempfile
import unittest
from pathlib import Path

from gg_desktop import squad_core as sq
from gg_desktop import squad_profile as sp


def setup(game="Skyrim", names=("A", "B")):
    return sq.Setup(game, [sq.Item("mo2", n.casefold(), n) for n in names], read_any=True)


class Codes(unittest.TestCase):
    def test_a_code_is_found_inside_a_chat_message_or_broken_over_lines(self):
        code = sq.make_code(setup())
        self.assertEqual(sq.find_code(code), code)
        self.assertEqual(sq.find_code(f"yo here's my mods:\n{code}\npaste it in game grave"), code)
        self.assertEqual(sq.find_code(code[:20] + "\n" + code[20:40] + " " + code[40:]), code)
        self.assertEqual(sq.find_code("no code here"), "")
        self.assertEqual([i.label for i in sq.read_code(f"Alex: {code} !!").items], ["A", "B"])
        with self.assertRaisesRegex(ValueError, "not a Squad Sync code"):
            sq.read_code("nonsense")

    def test_code_files(self):
        with tempfile.TemporaryDirectory() as temp:
            code = sq.make_code(setup())
            plain = Path(temp) / "message.txt"
            plain.write_text("Game Grave squad code\n" + code + "\n", encoding="utf-8")
            wide = Path(temp) / "wide.txt"
            wide.write_text(code, encoding="utf-16")
            self.assertEqual(sq.read_code_file(plain), code)
            self.assertEqual(sq.read_code_file(wide), code)
            self.assertEqual(sq.read_code_file(Path(temp) / "missing.txt"), "")
            big = Path(temp) / "big.txt"
            big.write_bytes(b"x" * (sq.MAX_CODE_FILE_BYTES + 1))
            self.assertEqual(sq.read_code_file(big), "")

    def test_share_steps_say_what_to_do_and_warn_about_long_codes(self):
        short = sq.share_steps(setup(), "GGSQ1-" + "a" * 100)
        self.assertIn("paste it to your friends", short)
        self.assertIn("Paste a friend's code", short)
        self.assertNotIn("more than one Discord message", short)
        long = sq.share_steps(setup(), "GGSQ1-" + "a" * 3000)
        self.assertIn("Save code as file", long)

    def test_your_own_code_is_recognised(self):
        mine = setup()
        self.assertTrue(sq.same_setup(mine, sq.read_code(sq.make_code(mine))))
        self.assertFalse(sq.same_setup(mine, setup(names=("A", "C"))))
        self.assertFalse(sq.same_setup(mine, setup(game="Fallout 4")))
        self.assertFalse(sq.same_setup(mine, None))

    def test_next_step_in_words(self):
        mine = setup(names=("A",))
        missing = sq.compare(setup(names=("A", "B")), mine)
        self.assertIn("Get what's missing", sq.next_step(missing, can_fetch=True, can_profile=True))
        self.assertIn("where your friend did", sq.next_step(missing, can_fetch=False, can_profile=True))
        match = sq.compare(setup(names=("A",)), mine)
        self.assertIn("Make squad profile", sq.next_step(match, can_fetch=False, can_profile=True))
        self.assertIn("Nothing left to do", sq.next_step(match, can_fetch=False, can_profile=False))
        self.assertEqual(sq.next_step(None, can_fetch=True, can_profile=True), "")


class Profile(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        root = Path(self.tmp.name)
        self.mods = root / "mods"
        for name in ("SkyUI", "USSEP", "Mine", "Fresh"):
            (self.mods / name).mkdir(parents=True)
        self.profile = root / "profiles" / "Default"
        self.profile.mkdir(parents=True)
        self.original = "# This file was automatically generated by Mod Organizer.\r\n+Mine\r\n-SkyUI\r\n+USSEP\r\n-Tools_separator\r\n*DLC: Dawnguard\r\n"
        (self.profile / "modlist.txt").write_bytes(self.original.encode("utf-8"))
        (self.profile / "plugins.txt").write_text("*Mine.esp\n", encoding="utf-8")
        (self.profile / "settings.ini").write_text("[General]\nLocalSaves=false\n", encoding="utf-8")

    def test_host_order_wins_everything_else_is_off(self):
        text, on, absent = sp.build_modlist(self.original, ["USSEP", "skyui", "Fresh", "NotHere", "USSEP"],
                                            ["SkyUI", "USSEP", "Mine", "Fresh"])
        self.assertEqual(on, ["USSEP", "SkyUI", "Fresh"])
        self.assertEqual(absent, ["NotHere"])
        self.assertEqual(text.split("\r\n"), ["# This file was automatically generated by Mod Organizer.", "+USSEP", "+SkyUI",
                                              "+Fresh", "-Mine", "-Tools_separator", "*DLC: Dawnguard", ""])

    def test_make_writes_a_new_profile_and_leaves_yours_alone(self):
        result = sp.make(self.profile, ["USSEP", "SkyUI", "Gone"], self.mods)
        folder = Path(result["folder"])
        self.assertEqual(folder.name, "GG Squad - Default")
        self.assertTrue((folder / sp.MARKER).is_file())
        self.assertEqual((folder / "plugins.txt").read_text(encoding="utf-8"), "*Mine.esp\n")
        self.assertTrue((folder / "modlist.txt").read_bytes().decode("utf-8").startswith("# This file"))
        self.assertIn("+USSEP\r\n+SkyUI\r\n-Mine", (folder / "modlist.txt").read_bytes().decode("utf-8"))
        self.assertEqual((self.profile / "modlist.txt").read_bytes().decode("utf-8"), self.original)
        self.assertEqual(result["not_installed"], ["Gone"])
        words = sp.result_text(result)
        self.assertIn("Your own profile was not changed", words)
        self.assertIn("1 is not installed here yet", words)
        again = sp.make(self.profile, ["USSEP"], self.mods)
        self.assertEqual(Path(again["folder"]).name, "GG Squad 2 - Default", "An existing squad profile is never overwritten")

    def test_refusals_in_words(self):
        with self.assertRaisesRegex(sp.ProfileError, "no Mod Organizer 2 mods"):
            sp.preview(self.profile, [], self.mods)
        with self.assertRaisesRegex(sp.ProfileError, "Get the missing mods first"):
            sp.preview(self.profile, ["Nope"], self.mods)
        with self.assertRaisesRegex(sp.ProfileError, "mods folder"):
            sp.preview(self.profile, ["SkyUI"], self.mods / "missing")
        (self.profile / "modlist.txt").unlink()
        with self.assertRaisesRegex(sp.ProfileError, "modlist"):
            sp.preview(self.profile, ["SkyUI"], self.mods)
        self.assertEqual([p.name for p in self.profile.parent.iterdir()], ["Default"])

    def test_own_saves_are_mentioned_not_refused(self):
        (self.profile / "settings.ini").write_text("[General]\nLocalSaves=true\n", encoding="utf-8")
        result = sp.make(self.profile, ["SkyUI"], self.mods)
        self.assertTrue(result["own_saves"])
        self.assertIn("starts without them", sp.result_text(result))


if __name__ == "__main__":
    unittest.main()


class NextStepAfterInstall(unittest.TestCase):
    def test_installed_but_off_and_profile_made(self):
        missing = sq.compare(setup(names=("A", "B")), setup(names=("A",)))
        self.assertIn("Every mod your friend has is installed", sq.next_step(missing, can_fetch=False, can_profile=True, still_missing=0))
        both = sq.next_step(missing, can_fetch=False, can_profile=True, still_missing=1)
        self.assertIn("get the 1 missing mod where your friend did", both)
        self.assertTrue(both.endswith("then press Make squad profile."))
        self.assertEqual(sq.next_step(missing, can_fetch=True, can_profile=True, profile_made="GG Squad - Default"),
                         'Last step: open Mod Organizer 2 and pick the profile "GG Squad - Default".')
